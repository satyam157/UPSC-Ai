def detect_subjects(query):
    """Detect which subjects the user is asking about from their query."""
    query_lower = query.lower()
    matched = []
    for subject, keywords in SUBJECT_KEYWORDS.items():
        for kw in keywords:
            if kw in query_lower:
                if subject not in matched:
                    matched.append(subject)
                break
    return matched if matched else list(ALL_SUBJECTS.keys())

def get_subject_strategy_text(subject_key):
    """Get compact strategy text for a subject to inject into LLM prompt."""
    subj = ALL_SUBJECTS.get(subject_key)
    if not subj:
        return ""
    lines = [f"\n## {subj['name']} — Strategy"]
    lines.append(f"Book: {subj['book']} | Weight: {subj['weight']} | Avg Qs: {subj['avg_qs']}")
    lines.append(f"Revision: {subj['revision']}")
    lines.append(f"Short Notes: {subj['short_notes']}")
    lines.append("### Chapter-wise Focus:")
    for ch in subj["chapters"]:
        focus_str = ", ".join(ch["focus"][:4])
        lines.append(f"- **{ch['ch']}** [Priority: {ch['priority']}] [Revise: {ch['revisions']}x] [Notes: {'Yes' if ch.get('notes') else 'No'}] — Focus: {focus_str} | PYQ: {ch['pyq']}")
    lines.append("Tips: " + " | ".join(subj["tips"]))
    return "\n".join(lines)

